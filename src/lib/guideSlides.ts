/**
 * 使い方ガイドの中身（スライドの文章・画面写真・画面の見方）。
 *
 * 使い方ページ（/guide）・作業しながら見るガイドの枠（components/GuidePanel.tsx）・
 * 印刷用ページ（/guide/print）が、すべてここを読む（同じ説明を2か所に書かない）。
 * 誰にどのスライドを出すか・並び・画面との対応は lib/guideMap.ts。
 *
 * 画面と一緒に更新できるよう、資料ファイルではなくアプリの中に置く。
 * 生産管理部・調達部だけが使う機能のスライドは、権限のある人にだけ出す
 * （使えない機能の説明を現場に読ませない）。
 * プラ箱のスライドは、工場間の送付を設定している会社だけに出す。
 *
 * 各スライドには、説明している画面の実物（public/guide/*.webp）を添える。
 * 架空のサンプルデータ（大口工場・山田 太郎 など）を入れた環境で撮ったもので、
 * スマホ画面は幅390pxの2倍、PCだけで使う画面はPCの幅で撮っている。
 * 画面の文言を変えたら、説明だけでなく画像も撮り直すこと（食い違うと現場が迷う）。
 *
 * 各スライドの parts は「画面の見方」（入力欄・ボタン・表示・札・色の意味）。
 * 画面の文言・出る条件・色の閾値（差異率5%など）は各画面のコードから書き起こしている。
 * 画面や判定の条件を変えたら、ここの説明も合わせて直すこと。
 */

/**
 * スライドに添える実画面のキャプチャ（public/guide/ に置く）。
 * width/height は画像の実寸。縦横比の枠を先に取って、読み込み中に表示が跳ねないようにする。
 */
export interface GuideShot {
  src: string;
  /** 画面に何が写っているか。読み上げと、画像が出ないときの代わりになる */
  alt: string;
  width: number;
  height: number;
  /**
   * PC画面のキャプチャ（横長・等倍）。スライドの幅いっぱいに出す。
   * 省略時はスマホ画面（幅390pxの2倍で撮ったもの）として扱う。
   */
  pc?: boolean;
}

/**
 * 「画面の見方」に出す見た目の手がかり。画面と同じ色の札・ボタンの形で見出しを出し、
 * 説明の文字だけで画面のどこの話かを探させない（色はアプリの各画面と揃える）。
 */
export type GuideTone =
  /** 青の塗り … 重量計を撮って読み取る操作 */
  | "read"
  /** オレンジの塗り … 記録する・登録する（その画面の主な操作） */
  | "action"
  /** 緑の塗り … 承認する */
  | "approve"
  /** 白地に灰色の枠 … 補助の操作（CSV・やめる など） */
  | "sub"
  /** 白地にオレンジの枠 … 袋を交換する・締め値を直す */
  | "subAccent"
  /** 白地に赤の枠 … 取り消す・戻す */
  | "danger"
  /** 黒の塗り … 選んでいる選択肢（職場・どこのスクラップか） */
  | "selected"
  /** 状態の札: 承認済み・処理済（緑） */
  | "ok"
  /** 状態の札: 承認待ち・申請中・未処理（黄） */
  | "wait"
  /** 状態の札: 差し戻し・要確認（赤） */
  | "ng"
  /** 状態の札: 下書き（灰） */
  | "draft"
  /** 状態の札: 記録中の袋（オレンジ） */
  | "open"
  /** AI読取の印（青） */
  | "ai"
  /** 他工場から届いたプラ箱の印（青） */
  | "poly"
  /** 赤字の注意・赤くなる数字 */
  | "alert";


/**
 * 画面の部品1つ分の説明（入力欄・ボタン・表示・札・色）。
 * 意味と「いつ使うか／押すと何が起きるか／誰に出るか／できない条件」を1〜2文で書く。
 * 文言は必ず実際の画面（コード）と揃える。画面を変えたらここも直す。
 */
export interface GuidePart {
  /**
   * 見出し。画面の文言そのものは「」で囲む（例「投入完了として記録する」）。
   * tone を付けたときは画面と同じ札・ボタンの形で出すので「」は付けない。
   */
  label: string;
  tone?: GuideTone;
  text: string;
}

/** スライド1枚分の中身。ページ側でデータとして書く。 */
export interface GuideSlide {
  /** スライドの id（lib/guideMap.ts。使い方ページのアンカーを兼ねるので変えない） */
  id: GuideSlideId;
  /** 見出しの上に出す小さなラベル（例「日次記録 ①」） */
  eyebrow: string;
  title: string;
  /** 見出しの下の1〜2行。何のための操作かを先に言う */
  lead: string;
  /** 手順・要点。番号は付けず、短く区切る */
  points: string[];
  /** 特に間違えやすい点。赤系で目立たせる */
  caution?: string;
  /**
   * 説明している画面の実物（1〜2枚）。文言（ボタン名など）は必ずこの画面と揃える。
   * 2枚のときは手順の順に並べる（例: カメラ画面 → 読み取ったあとの画面）。
   */
  shots?: GuideShot[];
  /**
   * 画面の見方（各部の意味）。手順（points）を読んだあとに、画面のどこが何かを
   * 確かめたい人向け。スマホで長くならないよう、開閉できる欄にまとめて出す。
   */
  parts?: GuidePart[];
}

