/** スマホ画面のキャプチャ */
function phone(name: keyof typeof SHOT_SIZE, alt: string): GuideShot {
  const [width, height] = SHOT_SIZE[name];
  return { src: `/guide/${name}.webp`, alt, width, height };
}

/** PC画面のキャプチャ（マスタ・取込・照合など、PCで使う画面） */
function pc(name: keyof typeof SHOT_SIZE, alt: string): GuideShot {
  return { ...phone(name, alt), pc: true };
}

